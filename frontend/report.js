/* InvoiceGuard AI: dependency-free PDF report generator.
 *
 * Builds a small, branded "invoice discrepancy report" PDF entirely in the
 * browser (PDF 1.4, Helvetica base-14 fonts, WinAnsi text, no compression,
 * no external libraries) so it can be attached to an e-mail / sent to the
 * vendor straight after an analysis.
 *
 * Public API: window.InvoiceGuardPDF.buildReportPdf(report, sessionId)
 * Returns a Uint8Array containing the PDF bytes.
 */
"use strict";

(function () {
  const PAGE_W = 595.28;
  const PAGE_H = 841.89;
  const MARGIN = 45;
  const CONTENT_W = PAGE_W - MARGIN * 2; // 505.28
  const TOP_Y = 790;
  const BOTTOM_Y = 68;
  const FOOTER_TEXT =
    "Generated by InvoiceGuard AI · informational support for reviewers and never authorizes payment.";

  /* brand palette */
  const C = {
    brand: [0.145, 0.388, 0.922],
    ink: [0.059, 0.09, 0.165],
    muted: [0.392, 0.455, 0.545],
    line: [0.886, 0.91, 0.941],
    zebra: [0.965, 0.973, 0.984],
    ok: [0.086, 0.639, 0.29],
    okSoft: [0.863, 0.988, 0.906],
    danger: [0.863, 0.149, 0.149],
    dangerSoft: [0.988, 0.925, 0.925],
    warn: [0.851, 0.467, 0.024],
    warnSoft: [0.996, 0.953, 0.78],
    gray: [0.929, 0.941, 0.953],
  };

  const STATUS_COLOR = {
    MATCHED: C.ok,
    DISCREPANCY_FOUND: C.warn,
    NEEDS_REVIEW: C.danger,
  };
  const SEVERITY_COLOR = { CRITICAL: C.danger, WARNING: C.warn, INFO: C.muted };

  /* approximate Helvetica advance widths (per 1000 em) for the characters
   * we emit; only used for truncation/wrapping and right alignment. */
  const W_BASE = {
    " ": 278, "!": 278, '"': 355, "#": 556, $: 556, "%": 889, "&": 667, "'": 191,
    "(": 333, ")": 333, "*": 389, "+": 584, ",": 278, "-": 333, ".": 278, "/": 278,
    "0": 556, "1": 556, "2": 556, "3": 556, "4": 556, "5": 556, "6": 556,
    "7": 556, "8": 556, "9": 556, ":": 278, ";": 278, "<": 584, "=": 584,
    ">": 584, "?": 556, "@": 1015,
    A: 667, B: 667, C: 722, D: 722, E: 667, F: 611, G: 778, H: 722, I: 278,
    J: 500, K: 667, L: 556, M: 833, N: 722, O: 778, P: 667, Q: 778, R: 722,
    S: 667, T: 611, U: 722, V: 667, W: 944, X: 667, Y: 667, Z: 611,
    "[": 278, "]": 278, "\\": 500, "_": 556,
  };
  const LOWER = { a: 556, b: 556, c: 500, d: 556, e: 556, f: 278, g: 556, h: 556, i: 222, j: 222, k: 500, l: 222, m: 833, n: 556, o: 556, p: 556, q: 556, r: 333, s: 500, t: 278, u: 556, v: 500, w: 722, x: 500, y: 500, z: 500 };
  Object.assign(W_BASE, LOWER);
  const BOLD_EXTRA = 1.08; // Helvetica-Bold is slightly wider

  function widthOf(text, size, bold) {
    let w = 0;
    for (const ch of String(text)) w += W_BASE[ch] || 556;
    return (w / 1000) * size * (bold ? BOLD_EXTRA : 1);
  }

  /* ---------------------------------------------------- text sanitisation */
  function sanitize(text) {
    return String(text == null ? "" : text)
      .replace(/₹/g, "INR ")
      .replace(/•/g, "-")
      .replace(/→/g, "->")
      .replace(/…/g, "...")
      .replace(/[‘’]/g, "'")
      .replace(/[“”]/g, '"')
      .replace(/[\u2013\u2014]/g, "-")
      .replace(/[^\x20-\x7E\xA0-\xFF]/g, "?");
  }

  function esc(text) {
    return String(text).replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
  }

  function fmtINR(value) {
    const n = Number(value);
    if (!isFinite(n)) return "n/a";
    const neg = n < 0;
    const fixed = Math.abs(n).toFixed(2);
    const parts = fixed.split(".");
    const int = parts[0];
    // Indian grouping: 1,2,34,567
    let out = int;
    if (int.length > 3) {
      const last3 = int.slice(-3);
      const rest = int.slice(0, -3);
      out = rest.replace(/(\d+?)(?=(\d\d)+$)/g, "$1,") + "," + last3;
    }
    return "INR " + (neg ? "-" : "") + out + "." + parts[1];
  }

  /* ------------------------------------------------- low level PDF ops */
  function txt(ops, x, y, size, font, text, color) {
    ops.push(
      `BT /${font} ${size} Tf ${color.join(" ")} rg 1 0 0 1 ${x.toFixed(2)} ${y.toFixed(2)} Tm (${esc(sanitize(text))}) Tj ET`
    );
  }

  function rect(ops, x, y, w, h, color, strokeColor) {
    if (strokeColor) {
      ops.push(`${strokeColor.join(" ")} RG 0.6 w ${x.toFixed(2)} ${y.toFixed(2)} ${w.toFixed(2)} ${h.toFixed(2)} re S`);
    } else {
      const c = color || [0, 0, 0];
      ops.push(`${c.join(" ")} rg ${x.toFixed(2)} ${y.toFixed(2)} ${w.toFixed(2)} ${h.toFixed(2)} re f`);
    }
  }

  function hline(ops, x1, x2, y, color) {
    ops.push(`${color.join(" ")} RG 0.6 w ${x1.toFixed(2)} ${y.toFixed(2)} m ${x2.toFixed(2)} ${y.toFixed(2)} l S`);
  }

  function wrapText(text, maxWidth, size, bold) {
    const words = String(text).split(/\s+/).filter(Boolean);
    const lines = [];
    let line = "";
    for (const word of words) {
      const attempt = line ? line + " " + word : word;
      if (widthOf(attempt, size, bold) > maxWidth && line) {
        lines.push(line);
        line = word;
      } else {
        line = attempt;
      }
    }
    if (line) lines.push(line);
    return lines;
  }

  function truncateToWidth(text, maxWidth, size, bold) {
    const t = String(text);
    if (widthOf(t, size, bold) <= maxWidth) return t;
    let cut = t;
    while (cut.length > 1 && widthOf(cut + "...", size, bold) > maxWidth) cut = cut.slice(0, -1);
    return cut.trim() + "...";
  }

  function rightAligned(ops, xRight, y, size, text, color, bold) {
    const font = bold ? "F2" : "F1";
    const w = widthOf(text, size, bold);
    txt(ops, xRight - w, y, size, font, text, color);
  }

  function paragraph(ops, x, y, size, text, color, font, maxWidth, lineGap) {
    const lines = wrapText(text, maxWidth, size, font === "F2");
    lines.forEach((line, i) => {
      txt(ops, x, y - i * (lineGap || size * 1.35), size, font, line, color);
    });
    return y - lines.length * (lineGap || size * 1.35);
  }

  /* -------------------------------------------------------- report doc */
  function buildReportPdf(report, sessionId) {
    const pagesOps = [];
    let ops = [];
    let y = TOP_Y;

    function newPage() {
      pagesOps.push(ops);
      ops = [];
      y = TOP_Y;
    }
    function need(space) {
      if (y - space < BOTTOM_Y) newPage();
    }

    const status = (report.status || "REPORT").toUpperCase();
    const statusColor = STATUS_COLOR[status] || C.warn;
    const currency = report.effective_currency || "INR";
    const now = new Date();
    const dateStr = now.toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" });
    const timeStr = now.toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit" });

    /* page header (every page) */
    function drawHeader() {
      rect(ops, MARGIN, PAGE_H - 66, 13, 22, C.brand);
      txt(ops, MARGIN + 20, PAGE_H - 50, 16, "F2", "InvoiceGuard AI", C.ink);
      txt(ops, MARGIN + 20, PAGE_H - 63, 9, "F1", "Invoice vs Purchase Order discrepancy report", C.muted);
      const right = PAGE_W - MARGIN;
      txt(ops, right - widthOf(`Generated ${dateStr} ${timeStr}`, 8), PAGE_H - 50, 8, "F1", `Generated ${dateStr} ${timeStr}`, C.muted);
      const sid = String(sessionId || "");
      txt(ops, right - widthOf(`Session ${sid.slice(0, 19)}`, 8), PAGE_H - 62, 8, "F1", `Session ${sid.slice(0, 19)}`, C.muted);
      hline(ops, MARGIN, right, PAGE_H - 76, C.line);
    }
    drawHeader();
    y = PAGE_H - 96;

    /* verdict block */
    const badgeH = 20;
    rect(ops, MARGIN, y - badgeH + 4, 7, 12, statusColor);
    txt(ops, MARGIN + 13, y - 2, 13, "F2", status, statusColor);
    let py = paragraph(
      ops, MARGIN, y - 22, 9.5, String(report.summary || ""), C.ink, "F1", CONTENT_W
    );
    if (report.recommended_action) {
      py = paragraph(ops, MARGIN, py - 4, 9, "Recommended: " + report.recommended_action, C.muted, "F1", CONTENT_W);
    }
    y = py - 12;

    /* KPI strip */
    const matches = report.matches || [];
    const findings = report.discrepancies || [];
    const matchedCount = matches.filter((m) => m.matched).length;
    const excess = findings.reduce(
      (s, d) => s + (d.potential_excess_amount != null ? Number(d.potential_excess_amount) : 0),
      0
    );
    const kpis = [
      { label: "LINES COMPARED", value: String(matches.length) },
      { label: "MATCHED", value: `${matchedCount} / ${matches.length}` },
      { label: "FINDINGS", value: String(findings.length) },
      { label: "POTENTIAL EXCESS", value: excess > 0 ? fmtINR(excess) : "none", alert: excess > 0 },
    ];
    const gap = 10;
    const boxW = (CONTENT_W - gap * 3) / 4;
    const boxH = 44;
    need(boxH + 16);
    kpis.forEach((k, i) => {
      const bx = MARGIN + i * (boxW + gap);
      rect(ops, bx, y - boxH + 6, boxW, boxH, C.zebra);
      rect(ops, bx, y - boxH + 6, boxW, boxH, null, C.line);
      const valueSize = k.value.length > 12 ? 10.5 : 13;
      const valueLight = "INR " === k.value.slice(0, 4) && k.value.length > 14; // shrink long money strings
      txt(ops, bx + 10, y - 6, valueLight ? 9.5 : valueSize, "F2", k.value, k.alert ? C.danger : C.ink);
      txt(ops, bx + 10, y - boxH + 14, 6.7, "F1", k.label, C.muted);
    });
    y -= boxH + 14;

    /* amounts block */
    function poLineTotal(p) {
      if (p.line_total != null) return Number(p.line_total);
      if (p.quantity != null && p.unit_price != null) return Number(p.quantity) * Number(p.unit_price);
      return null;
    }
    const invoiceTotal = report.invoice_total != null ? Number(report.invoice_total) : null;
    let poTotal = null;
    (report.po_items || []).forEach((p) => {
      const t = poLineTotal(p);
      if (t != null) poTotal = (poTotal || 0) + t;
    });

    need(92);
    txt(ops, MARGIN, y, 11.5, "F2", "Amounts", C.ink);
    y -= 16;
    const rows = [
      ["Invoice total", invoiceTotal == null ? "not extracted" : fmtINR(invoiceTotal)],
      ["PO line totals", poTotal == null ? "no PO totals" : fmtINR(poTotal)],
      ["Difference", invoiceTotal == null || poTotal == null ? "n/a" : fmtINR(invoiceTotal - poTotal)],
      ["Potential excess (findings)", excess > 0 ? fmtINR(excess) : "none"],
    ];
    rows.forEach(([label, value]) => {
      txt(ops, MARGIN + 8, y, 9.5, "F1", label, C.muted);
      rightAligned(ops, PAGE_W - MARGIN - 8, y, 9.5, value, C.ink, true);
      hline(ops, MARGIN, PAGE_W - MARGIN, y - 6, C.line);
      y -= 20;
    });
    y -= 6;

    /* line item table */
    const COLS = {
      id: 51,
      item: 69,
      itemMaxW: 107,
      invQp: 270,
      invTotal: 352,
      poQp: 432,
      poTotal: 506,
      conf: 514,
    };
    function drawTableHead(my) {
      rect(ops, MARGIN, my - 15, CONTENT_W, 16, C.brand);
      txt(ops, COLS.id, my - 10.5, 8, "F2", "#", [1, 1, 1]);
      txt(ops, COLS.item, my - 10.5, 8, "F2", "Item", [1, 1, 1]);
      rightAligned(ops, COLS.invQp, my - 10.5, 8, "Qty x price", [1, 1, 1], true);
      rightAligned(ops, COLS.invTotal, my - 10.5, 8, "Total", [1, 1, 1], true);
      rightAligned(ops, COLS.poQp, my - 10.5, 8, "PO qty x price", [1, 1, 1], true);
      rightAligned(ops, COLS.poTotal, my - 10.5, 8, "PO total", [1, 1, 1], true);
      txt(ops, COLS.conf, my - 10.5, 8, "F2", "Conf.", [1, 1, 1]);
      return my - 16;
    }

    let ty = y;
    txt(ops, MARGIN, ty, 11.5, "F2", "Line items", C.ink);
    ty -= 16;
    ty = drawTableHead(ty);

    matches.forEach((m, i) => {
      const rowH = 15;
      if (ty - rowH < BOTTOM_Y) {
        newPage();
        ty = drawTableHead(y);
      }
      if (i % 2 === 1) rect(ops, MARGIN, ty - 12, CONTENT_W, rowH, C.zebra);
      const inv = m.invoice_item || {};
      const poi = m.po_item;
      const matched = m.matched;

      const confLabel = !matched ? "MISS" : (m.confidence || "LOW");
      const confColor = !matched ? C.danger : confLabel === "HIGH" ? C.ok : confLabel === "MEDIUM" ? C.warn : C.danger;

      txt(ops, COLS.id, ty - 4, 8, "F1", String(i + 1), C.muted);
      txt(ops, COLS.item, ty - 4, 8, "F1", truncateToWidth(sanitize(inv.description || "-"), COLS.itemMaxW, 8), C.ink);

      const invQP =
        inv.quantity != null || inv.unit_price != null
          ? `${inv.quantity != null ? Number(inv.quantity) : "-"} x ${inv.unit_price != null ? fmtINR(inv.unit_price) : "-"}`
          : "-";
      rightAligned(ops, COLS.invQp, ty - 4, 8, invQP, C.ink);
      rightAligned(
        ops, COLS.invTotal, ty - 4, 8,
        inv.line_total != null ? fmtINR(inv.line_total) : "-",
        C.ink
      );
      const poQP = poi ? `${Number(poi.quantity)} x ${fmtINR(poi.unit_price)}` : "-";
      rightAligned(ops, COLS.poQp, ty - 4, 8, poQP, C.ink);
      const poTotalValue = poi ? poLineTotal(poi) : null;
      rightAligned(ops, COLS.poTotal, ty - 4, 8, poTotalValue != null ? fmtINR(poTotalValue) : "-", C.ink);
      txt(ops, COLS.conf, ty - 4, 7.5, "F2", confLabel, confColor);

      ty -= rowH;
    });
    y = ty - 12;

    /* findings */
    txt(ops, MARGIN, y, 11.5, "F2", "Findings", C.ink);
    y -= 18;
    if (!findings.length) {
      txt(ops, MARGIN + 8, y, 9.5, "F1", "No discrepancies detected; deterministic validation passed.", C.ok);
      y -= 18;
    } else {
      findings.forEach((d) => {
        const color = SEVERITY_COLOR[d.severity] || C.muted;
        const blockH = 46;
        if (y - blockH < BOTTOM_Y) newPage();
        rect(ops, MARGIN, y - 6, 6, 6, color);
        txt(ops, MARGIN + 12, y - 4, 9.5, "F2", `${sanitize(d.type)} (${sanitize(d.severity)})`, color);
        let fy = paragraph(ops, MARGIN + 12, y - 18, 9, d.message, C.ink, "F1", CONTENT_W - 12);
        const bits = [];
        if (d.line_ref) bits.push(`item: ${d.line_ref}`);
        if (d.invoice_value != null) bits.push(`invoice: ${d.invoice_value}`);
        if (d.po_value != null) bits.push(`PO: ${d.po_value}`);
        if (d.difference != null) bits.push(`difference: ${d.difference}`);
        if (d.potential_excess_amount != null) bits.push(`potential excess: ${fmtINR(d.potential_excess_amount)}`);
        if (bits.length) {
          fy = paragraph(ops, MARGIN + 12, fy - 2, 8.5, bits.join("  |  "), C.ink, "F1", CONTENT_W - 12);
        }
        if (d.explanation) {
          fy = paragraph(ops, MARGIN + 12, fy - 2, 8.5, d.explanation, C.muted, "F1", CONTENT_W - 12);
        }
        y = fy - 10;
      });
    }

    /* extraction warnings */
    const warnings = (report.extraction_warnings || []).slice(0, 5);
    if (warnings.length) {
      need(50);
      txt(ops, MARGIN, y, 11.5, "F2", "Extraction notes", C.ink);
      y -= 16;
      warnings.forEach((w) => {
        const ny = paragraph(ops, MARGIN + 8, y, 8.5, "- " + w, C.muted, "F1", CONTENT_W - 8);
        y = ny - 4;
      });
    }

    /* closing page and build the objects */
    pagesOps.push(ops);
    pagesOps.forEach((pageOps, idx) => {
      /* footer */
      pageOps.push(
        `BT /F1 7.5 Tf ${C.muted.join(" ")} rg 1 0 0 1 ${MARGIN} 34 Tm (${esc(sanitize(FOOTER_TEXT))}) Tj ET`
      );
      rightAligned(pageOps, PAGE_W - MARGIN, 34, 7.5, `Page ${idx + 1} of ${pagesOps.length}`, C.muted);
      hline(pageOps, MARGIN, PAGE_W - MARGIN, 46, C.line);
    });

    const kids = pagesOps.map((_, i) => `${5 + 2 * i} 0 R`).join(" ");
    const objs = [];
    objs.push("1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n");
    objs.push(`2 0 obj\n<< /Type /Pages /Kids [${kids}] /Count ${pagesOps.length} >>\nendobj\n`);
    objs.push("3 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>\nendobj\n");
    objs.push("4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>\nendobj\n");
    pagesOps.forEach((pageOps, i) => {
      const content = pageOps.join("\n") + "\n";
      objs.push(
        `${5 + 2 * i} 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_W} ${PAGE_H}] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${6 + 2 * i} 0 R >>\nendobj\n`
      );
      objs.push(
        `${6 + 2 * i} 0 obj\n<< /Length ${content.length} >>\nstream\n${content}endstream\nendobj\n`
      );
    });

    let out = "%PDF-1.4\n%\xE2\xE3\xCF\xD3\n";
    const offsets = [];
    objs.forEach((o) => {
      offsets.push(out.length);
      out += o;
    });
    const xrefPos = out.length;
    out += `xref\n0 ${objs.length + 1}\n`;
    out += "0000000000 65535 f \n";
    offsets.forEach((o) => {
      out += String(o).padStart(10, "0") + " 00000 n \n";
    });
    out += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xrefPos}\n%%EOF\n`;

    const bytes = new Uint8Array(out.length);
    for (let i = 0; i < out.length; i++) {
      const code = out.charCodeAt(i);
      if (code > 255) throw new Error("non Latin-1 byte in PDF stream");
      bytes[i] = code;
    }
    return bytes;
  }

  window.InvoiceGuardPDF = { buildReportPdf };
})();
